import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { lstat, realpath } from 'node:fs/promises';
assert.equal(process.env.NODE_PATH, undefined, 'NODE_PATH must not mask a missing consumer dependency');
assert.equal(typeof globalThis.window, 'undefined');
assert.equal(typeof globalThis.document, 'undefined');
const packagePath = fileURLToPath(import.meta.resolve('@cloudlet/toast'));
assert(!((await lstat('node_modules/@cloudlet/toast')).isSymbolicLink()), 'tarball dependency must be extracted, not a workspace symlink');
assert((await realpath(packagePath)).startsWith(process.cwd() + '/node_modules/'), 'entrypoint must resolve from isolated node_modules');
const before = process.getActiveResourcesInfo().sort();
const api = await import('@cloudlet/toast');
const one = api.createCloudlet(), two = api.createCloudlet();
assert.notEqual(one, two);
assert.equal(one.show({ id: 'same', title: 'One' }).status, 'created');
assert.equal(two.show({ id: 'same', title: 'Two' }).status, 'created');
assert.equal(one.getServerSnapshot().notifications.length, 0);
assert.equal(one.getSnapshot().notifications[0].content.title, 'One');
assert.equal(two.getSnapshot().notifications[0].content.title, 'Two');
assert.deepEqual(process.getActiveResourcesInfo().sort(), before, 'cold import/controller must create no timers or resources');
one.dispose(); two.dispose();
console.log(JSON.stringify({ node: process.version, resolved: packagePath, css: fileURLToPath(import.meta.resolve('@cloudlet/toast/styles.css')), noDOM: true, noResourceStart: true }));
