import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const resolve = createRequire(join(root, 'package.json'));
const library = JSON.parse(await readFile(join(root, 'packages/toast/package.json'), 'utf8'));
const entries = new Map();

async function visit(name, from = resolve) {
  // Some runtimes intentionally do not export package.json. Resolve their entry,
  // then locate the owning manifest without bypassing runtime package exports.
  let directory = dirname(from.resolve(name));
  let manifestPath;
  while (true) {
    const candidate = join(directory, 'package.json');
    try {
      const value = JSON.parse(await readFile(candidate, 'utf8'));
      if (value.name === name) { manifestPath = candidate; break; }
    } catch (error) { if (error.code !== 'ENOENT') throw error; }
    const parent = dirname(directory);
    if (parent === directory) throw new Error(`Cannot locate manifest for ${name}`);
    directory = parent;
  }
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
  const key = `${manifest.name}@${manifest.version}`;
  if (entries.has(key)) return;
  let license;
  let source;
  for (const candidate of ['LICENSE', 'LICENSE.md', 'LICENSE.txt']) {
    try {
      // Preserve license wording while making generated bytes independent of
      // upstream CRLF and the checkout's core.autocrlf setting.
      license = (await readFile(join(dirname(manifestPath), candidate), 'utf8')).replace(/\r\n?/gu, '\n');
      source = candidate;
      break;
    }
    catch (error) { if (error.code !== 'ENOENT') throw error; }
  }
  if (!license) throw new Error(`No verified license text for ${key}`);
  entries.set(key, { license, source, manifest });
  for (const dependency of Object.keys(manifest.dependencies ?? {}).sort()) {
    await visit(dependency, createRequire(manifestPath));
  }
}

/**
 * Code ported into Cloudlet (size experiment E1): Motion is no runtime dependency since
 * then, but src/react/generators.ts carries its numeric spring and easing, so the MIT attribution
 * stays. The versions are the ones the port was taken from and the reference test runs against.
 */
const ported = {
  'motion-dom': 'src/react/generators.ts: numeric spring generator (animation/generators/spring.mjs) and the two-keyframe tween of keyframes.mjs',
  'motion-utils': 'src/react/generators.ts: cubicBezier easing (easing/cubic-bezier.mjs)',
};
for (const name of Object.keys({ ...library.dependencies, ...library.peerDependencies }).sort()) await visit(name);
for (const name of Object.keys(ported).sort()) await visit(name);
let text = '# Third-party notices\n\nGenerated from the installed lockfile dependency tree by `npm run notices`.\n'
  + 'Cloudlet bundles none of these runtimes and has no runtime dependencies; React/React DOM are peers.\n'
  + 'Versions below describe this development/consumer baseline, not the whole supported peer range.\n'
  + 'The numeric spring and easing generators in `src/react/generators.ts` are ported from Motion\n'
  + '(motion-dom and motion-utils, MIT) and keep its attribution below; nothing else was copied.\n\n';
for (const [key, { license, source, manifest }] of [...entries].sort(([a], [b]) => a.localeCompare(b))) {
  const port = ported[manifest.name];
  text += `## ${key}\n\nLicense: ${manifest.license}. Source: installed package ${source}.\n`
    + (port ? `Ported code: ${port}.\n` : '')
    + `\n\`\`\`text\n${license.trim()}\n\`\`\`\n\n`;
}
await writeFile(join(root, 'packages/toast/THIRD_PARTY_NOTICES.md'), `${text.trimEnd()}\n`);
await writeFile(join(root, 'packages/toast/LICENSE'), await readFile(join(root, 'LICENSE')));
console.log(`Verified license texts recorded for ${entries.size} installed runtime/peer packages.`);
