// Exports Blender renders (cloud-<n>-<day|night>.png) to AVIF + WebP at 1x/2x
// and writes the manifest the Sky component reads. sharp-cli runs through npx,
// outside the workspace, so it never enters package.json or the lock file.
//   node apps/site/scripts/clouds/export.mjs <renders-dir>
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SHARP = 'sharp-cli@6.1.0';
const WIDTHS = [800, 1600];
const QUALITY = { avif: 55, webp: 80 };

const site = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const source = resolve(process.argv[2] ?? '');
const target = join(site, 'public/sky');
mkdirSync(target, { recursive: true });

const pngSize = (file) => {
  const header = readFileSync(file);
  return { width: header.readUInt32BE(16), height: header.readUInt32BE(20) };
};

const renders = readdirSync(source).filter((name) => /^cloud-\d+-(day|night)\.png$/.test(name)).sort();
if (renders.length === 0) throw new Error(`No cloud renders in ${source}`);

const shapes = new Map();
for (const name of renders) {
  const [, id, theme] = name.match(/^cloud-(\d+)-(day|night)\.png$/);
  const input = join(source, name);
  const { width, height } = pngSize(input);
  shapes.set(Number(id), { width, height });
  for (const size of WIDTHS) {
    for (const format of ['avif', 'webp']) {
      const output = join(target, `cloud-${id}-${theme}-${size}.${format}`);
      execFileSync('npx', ['-y', SHARP, '-i', input, '-o', output, '-f', format, '-q', String(QUALITY[format]), 'resize', String(Math.min(size, width))], { cwd: tmpdir(), stdio: 'inherit' });
    }
  }
  console.log('exported', name);
}

const manifest = [...shapes].sort(([a], [b]) => a - b).map(([id, { width, height }]) => ({ id, aspect: Number((width / height).toFixed(4)) }));
writeFileSync(
  join(site, 'src/lib/clouds.generated.ts'),
  `// Generated by scripts/clouds/export.mjs from the Blender renders. Do not edit.\nexport const CLOUD_SHAPES = ${JSON.stringify(manifest, null, 2)} as const;\nexport const CLOUD_WIDTHS = ${JSON.stringify(WIDTHS)} as const;\n`,
);
console.log('manifest', manifest);
