// Exports the cloud wordmark renders (wordmark-<variant>-<day|night>.png from wordmark.py) to
// AVIF + WebP, makes each variant's halo (the mask that parts the sky's clouds around the letters)
// and writes the manifest the footer reads. Same tooling as export.mjs: sharp-cli through npx,
// outside the workspace.
//   node apps/site/scripts/clouds/export-wordmark.mjs <renders-dir>
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SHARP = 'sharp-cli@6.1.0';
// The sky's widths: soft cloud edges hold up when a 2x screen upscales 1600 (2880 cost ~5x the bytes).
const WIDTHS = [800, 1600];
const QUALITY = { avif: 55, webp: 80 };
const PATTERN = /^wordmark-([a-z]+)-(day|night)\.png$/;
// Halo: the render's alpha at HALO_WIDTH px, padded by HALO_PAD of the width on every side (room to
// grow past the image edge), grown by blur + threshold (~3% of the width), then feathered as much.
const HALO_WIDTH = 256;
const HALO_PAD = 0.06;
const HALO_GROW = { blur: 4, threshold: 24 };
const HALO_FEATHER = 4;

const site = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const source = resolve(process.argv[2] ?? '');
const target = join(site, 'public/wordmark');
mkdirSync(target, { recursive: true });

const pngSize = (file) => {
  const header = readFileSync(file);
  return { width: header.readUInt32BE(16), height: header.readUInt32BE(20) };
};

const renders = readdirSync(source).filter((name) => PATTERN.test(name)).sort();
if (renders.length === 0) throw new Error(`No wordmark renders in ${source}`);

const sharp = (input, output, ...operations) =>
  execFileSync('npx', ['-y', SHARP, '-i', input, '-o', output, ...operations], { cwd: tmpdir(), stdio: 'inherit' });

/** Opaque where the sky's clouds must give way to the letters, transparent elsewhere (an alpha mask:
 * Chrome ignores mask-mode: luminance on images). */
function halo(render, output) {
  const work = mkdtempSync(join(tmpdir(), 'wordmark-halo-'));
  const pad = String(Math.round(HALO_WIDTH * HALO_PAD));
  const step = (name) => join(work, `${name}.png`);
  sharp(render, step('alpha'), 'extractChannel', 'alpha', '--', 'resize', String(HALO_WIDTH));
  sharp(step('alpha'), step('padded'), 'extend', pad, pad, pad, pad, '--background', 'black');
  sharp(step('padded'), step('grown'), 'blur', String(HALO_GROW.blur), '--', 'threshold', String(HALO_GROW.threshold));
  sharp(step('grown'), step('feathered'), 'blur', String(HALO_FEATHER));
  sharp(step('feathered'), step('white'), 'linear', '0', '--offset', '255');
  sharp(step('white'), output, 'joinChannel', step('feathered'));
  rmSync(work, { recursive: true });
}

const variants = new Map();
for (const name of renders) {
  const [, variant, theme] = name.match(PATTERN);
  const input = join(source, name);
  const { width, height } = pngSize(input);
  variants.set(variant, { width, height });
  for (const size of WIDTHS) {
    for (const format of ['avif', 'webp']) {
      const output = join(target, `wordmark-${variant}-${theme}-${size}.${format}`);
      sharp(input, output, '-f', format, '-q', String(QUALITY[format]), 'resize', String(Math.min(size, width)));
    }
  }
  if (theme === 'day') halo(input, join(target, `wordmark-${variant}-halo.png`));
  console.log('exported', name);
}

const manifest = [...variants].sort(([a], [b]) => a.localeCompare(b)).map(([id, { width, height }]) => ({ id, aspect: Number((width / height).toFixed(4)) }));
writeFileSync(
  join(site, 'src/lib/wordmark.generated.ts'),
  `// Generated by scripts/clouds/export-wordmark.mjs from the Blender renders. Do not edit.\nexport const WORDMARKS = ${JSON.stringify(manifest, null, 2)} as const;\nexport const WORDMARK_WIDTHS = ${JSON.stringify(WIDTHS)} as const;\n/** The halo images extend past the render by this share of its width on every side. */\nexport const WORDMARK_HALO_PAD = ${Math.round(HALO_WIDTH * HALO_PAD) / HALO_WIDTH};\n`,
);
console.log('manifest', manifest);
